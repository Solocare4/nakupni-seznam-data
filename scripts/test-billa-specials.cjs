const assert=require('node:assert/strict');
const {selectPublicationSlug}=require('./update-billa.cjs');
const html='https://view.publitas.com/billa-cz/velky-letak-16-9-22-9-2026/page/1 https://view.publitas.com/billa-cz/maly-letak-16-9-22-9-2026/page/1';
assert.equal(selectPublicationSlug(html,'https://www.billa.cz/letaky-billa?tab=letaky-billa/maly-letak'),'maly-letak-16-9-22-9-2026');
assert.equal(selectPublicationSlug(html,'https://www.billa.cz/letaky-billa?tab=letaky-billa/velky-letak'),'velky-letak-16-9-22-9-2026');
assert.throws(()=>selectPublicationSlug(html,'https://www.billa.cz/akcni-letaky/special-bilovec'));
assert.throws(()=>selectPublicationSlug(html+' https://view.publitas.com/billa-cz/maly-letak-23-9-29-9-2026','https://www.billa.cz/letaky-billa?tab=letaky-billa/maly-letak'));
console.log('OK: BILLA selects exact format, rejects missing and ambiguous publications');
const special='https://view.publitas.com/billa-cz/special-pstruzi-14-10-20-10-2026';
assert.equal(selectPublicationSlug(special,'https://www.billa.cz/akcni-letaky/special-pstruzi2'),'special-pstruzi-14-10-20-10-2026');
assert.throws(()=>selectPublicationSlug(special,'https://www.billa.cz/akcni-letaky/special-brno2'));
assert.throws(()=>selectPublicationSlug(special+' '+special.replace('14-10-20','21-10-27'),'https://www.billa.cz/akcni-letaky/special-pstruzi2'));
const {collectSpecials}=require('./billa-specials.cjs');
const {applyReviewed}=require('../scripts/billa-reviewed.cjs');
const reviewed={publicationSlug:'special-pstruzi-14-10-20-10-2026',pdfSha256:'08fe9389a99901facde27171911d26a5ad9268936961a3514e7034b03680ff37',offers:[{productName:'Špekáčky',price:12.9,quantity:100,unit:'g',validFrom:'2026-10-14',validTo:'2026-10-20',sourceUrl:'https://www.billa.cz/akcni-letaky/special-pstruzi2',flyerUrl:'https://view.publitas.com/example.pdf#page=2'}]};
assert.equal(applyReviewed(reviewed).offers.length,7);
assert.equal(applyReviewed(applyReviewed(reviewed)).offers.length,7,'Repeated review is idempotent');
assert.equal(applyReviewed({...reviewed,pdfSha256:'changed'}).offers.length,1,'Do not apply old review to revised PDF');
assert.equal(applyReviewed({...reviewed,publicationSlug:'another-week'}).offers.length,1);
assert.equal(applyReviewed(reviewed).offers.find(o=>o.productName.startsWith('Kobliha')).price,14.9,'Non-member price, not club price');
(async()=>{
 const base='https://www.billa.cz/akcni-letaky/special-';
 const stores=[{id:'brno-one',city:'Brno',street:'Hlavní 1'},{id:'ostrava-one',city:'Ostrava',street:'Dlouhá 2'}];
 const result=await collectSpecials([base+'ostrava2',base+'brno',base+'ostrava'],stores,stores,async({pageUrl})=>{
  if(pageUrl.endsWith('ostrava2'))throw Error('Chybějící publikace');
  return {publicationText:'Brno, ulice Hlavní',offers:[{id:pageUrl,price:9.9}]};
 });
 assert.equal(result.offers.length,1,'A broken local link does not abort later verified publications');
 assert.deepEqual(result.offers[0].applicableBranchIds,['brno-one'],'Local offers never become national');
 assert.equal(result.issues.length,2,'Both missing publication and unverified scope remain visible in diagnostics');
 assert.equal(result.skipped,1,'Unknown missing-publication size is not invented');
 const pstruzi={id:'billa-82-745',city:'Pstruží',street:'Pstruží 389'};
 const fetchSpecial=async()=>({publicationText:'Akce platí pouze na prodejně Pstruží. ULICE FRENŠTÁTSKÁ',offers:[{id:'special',price:12.9}]});
 const recovered=await collectSpecials([base+'pstruzi2'],[pstruzi],[pstruzi],fetchSpecial);
 assert.deepEqual(recovered.offers[0].applicableBranchIds,[pstruzi.id]);
 const ambiguous=await collectSpecials([base+'pstruzi2'],[pstruzi,{...pstruzi,id:'second'}],[pstruzi],fetchSpecial);
 assert.equal(ambiguous.offers.length,0,'City-only proof is not enough when multiple stores share the city');
 console.log('OK: BILLA local publication failures remain explicit without blocking verified offers');
})().catch(e=>{console.error(e);process.exitCode=1});
